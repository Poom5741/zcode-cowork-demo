def build_row(code, name, region):
    in_store = random.randint(800_000, 2_500_000)
    online = random.randint(300_000, 1_200_000)
    promo = random.randint(100_000, 600_000)
    staff = random.randint(8, 25)
    expense = int((in_store + online + promo) * random.uniform(0.55, 0.75))
    note = random.choice(["", "", "", "มีงานออกบูธนอกสถานที่ 2 ครั้ง", "ลูกค้าเบิกคืนสินค้า 3 รายการ"])
    return [code, name, region, in_store, online, promo, staff, expense, note]

def save_workbook(path, rows, month="ตุลาคม 2568"):
    wb = Workbook(); ws = wb.active; ws.title = "รายงานยอดขาย"
    ws.append([f"รายงานยอดขายประจำเดือน {month} — บริษัท สยาม รีเทล กรุ๊ป จำกัด"])
    ws.append([]); ws.append(HEADERS)
    for r in rows: ws.append(r)
    ws.append([])
    ws.append(["รวมทั้งสาขา", "", "", f"=SUM(D4:D{3+len(rows)})", f"=SUM(E4:E{3+len(rows)})",
               f"=SUM(F4:F{3+len(rows)})", "", f"=SUM(H4:H{3+len(rows)})", ""])
    wb.save(path)

